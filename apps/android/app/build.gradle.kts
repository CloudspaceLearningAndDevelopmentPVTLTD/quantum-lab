android {
    namespace = "ai.qubit16.app"
    compileSdk = 36

    defaultConfig {
        applicationId = "ai.qubit16.app"
        // 26 (Android 8.0), not lower: adaptive icons are API 26+, so this
        // keeps the icon vector-only with no fabricated raster fallback, and
        // by 2026 API <26 is a statistically negligible slice of active
        // devices. Notification channels (used by the delegation service)
        // are also 26+.
        minSdk = 26
        targetSdk = 36
        versionCode = 2
        versionName = "1.0.0"

        // The TWA library (androidbrowserhelper) reads this to know which
        // origin it is verifying and launching — see AndroidManifest.xml's
        // <meta-data android:name="asset_statements">, which points back to
        // this same host. Kept in one place so the two can never drift.
        manifestPlaceholders["hostName"] = "qubit16.ai"
        // ?app=android marks the session as the Play Store app, so the site
        // hides every purchase entry point (Play's payments policy). Chrome's
        // android-app:// referrer does the same job; this is the second signal.
        // See apps/web/lib/app-shell.ts.
        manifestPlaceholders["defaultUrl"] = "https://qubit16.ai/?app=android"
    }

    // Signing comes from the environment so the key and its passwords never
    // touch a file in this repo. With QUBIT16_KEYSTORE unset (the default, and
    // CI) there is no signing config and the release build stays unsigned,
    // exactly as before. See docs/ANDROID.md "Signing for release".
    val keystorePath: String? = System.getenv("QUBIT16_KEYSTORE")
    if (keystorePath != null) {
        signingConfigs {
            create("release") {
                storeFile = file(keystorePath)
                storePassword = System.getenv("QUBIT16_KEYSTORE_PASSWORD")
                keyAlias = System.getenv("QUBIT16_KEY_ALIAS")
                keyPassword = System.getenv("QUBIT16_KEY_PASSWORD")
            }
        }
    }

    buildTypes {
        release {
            signingConfigs.findByName("release")?.let { signingConfig = it }
            isMinifyEnabled = true
            isShrinkResources = true
            proguardFiles(getDefaultProguardFile("proguard-android-optimize.txt"), "proguard-rules.pro")
            // Unsigned here on purpose — see docs/ANDROID.md "Signing for
            // release". A release build passes a real signing config via
            // -Pandroid.injected.signing.store.file=... at build time; the
            // key itself is never generated by or committed to this repo.
        }
        debug {
            // No custom signingConfig: AGP's own well-known auto-generated
            // debug keystore (~/.android/debug.keystore) signs debug builds,
            // which is the standard, zero-setup default for local builds.
            applicationIdSuffix = ".debug"
        }
    }

    compileOptions {
        sourceCompatibility = JavaVersion.VERSION_17
        targetCompatibility = JavaVersion.VERSION_17
    }
    kotlinOptions {
        jvmTarget = "17"
    }

    buildFeatures {
        viewBinding = false
        buildConfig = true
    }

    packaging {
        resources {
            excludes += "/META-INF/{AL2.0,LGPL2.1}"
        }
    }
}

