/**
 * lib/glossary/terms.ts — the quantum glossary.
 *
 * A glossary on a site like this earns its place only if each entry does two
 * things a dictionary cannot: say the idea plainly WITHOUT the usual misleading
 * metaphor, and send you to the place on this site where you can watch it
 * happen. Hence `see`: every entry links to at least one lesson, visualization,
 * challenge or tool, and `terms.test.ts` fails if any of those links is dead.
 *
 * RULES FOR EDITING THIS FILE:
 *   · `short` is one sentence and must stand alone — it is what search and the
 *     A–Z list show.
 *   · `body` corrects the common misconception where there is one. "It is in
 *     both states at once" and "it sends information faster than light" are the
 *     two this file exists to stop repeating.
 *   · `formula` is plain Unicode, not LaTeX: it renders everywhere, including in
 *     the JSON-LD a search engine reads.
 *   · `related` and `see` are validated. Add a term, and the test tells you if
 *     it points anywhere that does not exist.
 *
 * Not imported by the global client graph (search, nav): the /glossary page is
 * the only consumer, so the prose ships only to people who open it.
 */

