export interface CodePreset {
  id: string
  name: string
  /** The parameters the literature gives; the tests check analyseCode agrees. */
  params: [n: number, k: number, d: number]
  generators: string[]
  note: string
  /** Error Correction Zoo entry. */
  zoo: string
}

function support(n: number, type: 'X' | 'Z', qubits: number[]): string {
  return Array.from({ length: n }, (_, q) => (qubits.includes(q) ? type : 'I')).join('')
}

function rotatedSurface3(): string[] {
  return [
    support(9, 'X', [0, 1, 3, 4]),
    support(9, 'X', [4, 5, 7, 8]),
    support(9, 'X', [1, 2]),
    support(9, 'X', [6, 7]),
    support(9, 'Z', [1, 2, 4, 5]),
    support(9, 'Z', [3, 4, 6, 7]),
    support(9, 'Z', [0, 3]),
    support(9, 'Z', [5, 8]),
  ]
}

/** Qubits on the edges of an L×L torus: horizontal edges first, then vertical. */
function toric(L: number): string[] {
  const h = (r: number, c: number) => ((r + L) % L) * L + ((c + L) % L)
  const v = (r: number, c: number) => L * L + ((r + L) % L) * L + ((c + L) % L)
  const out: string[] = []
  for (let r = 0; r < L; r++) {
    for (let c = 0; c < L; c++) out.push(support(2 * L * L, 'X', [h(r, c), h(r, c - 1), v(r, c), v(r - 1, c)]))
  }
  for (let r = 0; r < L; r++) {
    for (let c = 0; c < L; c++) out.push(support(2 * L * L, 'Z', [h(r, c), h(r + 1, c), v(r, c), v(r, c + 1)]))
  }
  return out
}

/** Qubit q (0..14) is the binary number q+1; generator j is "bit j is set". */
function reedMuller15(): string[] {
  const bit = (j: number) => Array.from({ length: 15 }, (_, q) => q).filter((q) => ((q + 1) >> j) & 1)
  const both = (i: number, j: number) => bit(i).filter((q) => bit(j).includes(q))
  const out: string[] = []
  for (let j = 0; j < 4; j++) out.push(support(15, 'X', bit(j)))
  for (let j = 0; j < 4; j++) out.push(support(15, 'Z', bit(j)))
  for (let i = 0; i < 4; i++) for (let j = i + 1; j < 4; j++) out.push(support(15, 'Z', both(i, j)))
  return out
}

