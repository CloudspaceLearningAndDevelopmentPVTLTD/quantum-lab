/**
 * lib/qec/stabilizerCode.ts — what code did you just write down?
 *
 * Input: a list of Pauli strings. Output: whether they generate a valid
 * stabilizer group, and if so the code's [[n, k, d]], a basis of logical
 * operators, and whether it is degenerate.
 *
 * Everything is exact linear algebra over GF(2) on the symplectic
 * representation (Gottesman, quant-ph/9705052) except the distance, which is
 * a brute-force search by increasing weight. That search is exponential, so it
 * runs against a stated budget and reports a bracket (lower ≤ d ≤ upper)
 * rather than a guess when the budget runs out.
 *
 * A Pauli on n ≤ 30 qubits is two bitmasks; qubit q is bit q, and character q
 * of the string form.
 */

export const MAX_CODE_QUBITS = 30

export interface Pauli {
  x: number
  z: number
  /** 1 for a leading minus sign. */
  sign: 0 | 1
}

function popcount(v: number): number {
  v = v - ((v >>> 1) & 0x55555555)
  v = (v & 0x33333333) + ((v >>> 2) & 0x33333333)
  return (((v + (v >>> 4)) & 0x0f0f0f0f) * 0x01010101) >>> 24
}

export function parsePauli(text: string): { pauli: Pauli; n: number } {
  let body = text.trim()
  let sign: 0 | 1 = 0
  if (body.startsWith('+') || body.startsWith('-')) {
    sign = body[0] === '-' ? 1 : 0
    body = body.slice(1).trim()
  }
  let x = 0
  let z = 0
  for (let q = 0; q < body.length; q++) {
    const ch = body[q].toUpperCase()
    if (ch === 'X' || ch === 'Y') x |= 1 << q
    if (ch === 'Z' || ch === 'Y') z |= 1 << q
    if (!'IXYZ_.'.includes(ch)) throw new Error(`"${body[q]}" is not a Pauli. Use I, X, Y, Z (or _ for identity).`)
  }
  return { pauli: { x, z, sign }, n: body.length }
}

export function pauliString(p: Pick<Pauli, 'x' | 'z'>, n: number): string {
  let out = ''
  for (let q = 0; q < n; q++) {
    const xv = (p.x >>> q) & 1
    const zv = (p.z >>> q) & 1
    out += xv ? (zv ? 'Y' : 'X') : zv ? 'Z' : 'I'
  }
  return out
}

export const weight = (p: Pick<Pauli, 'x' | 'z'>): number => popcount(p.x | p.z)

export const commutes = (a: Pick<Pauli, 'x' | 'z'>, b: Pick<Pauli, 'x' | 'z'>): boolean =>
  (popcount((a.x & b.z) ^ (a.z & b.x)) & 1) === 0

/** a·b for COMMUTING Paulis, sign included. */
function multiply(a: Pauli, b: Pauli): Pauli {
  const plus = (a.x & a.z & b.z & ~b.x) | (a.x & ~a.z & b.z & b.x) | (~a.x & a.z & b.x & ~b.z)
  const minus = (a.x & a.z & b.x & ~b.z) | (a.x & ~a.z & b.z & ~b.x) | (~a.x & a.z & b.x & b.z)
  const total = (((2 * a.sign + 2 * b.sign + popcount(plus) - popcount(minus)) % 4) + 4) % 4
  return { x: a.x ^ b.x, z: a.z ^ b.z, sign: total & 2 ? 1 : 0 }
}

/** Lowest set bit of x, else of z — the pivot a reduced vector is filed under. */
function pivotOf(p: Pick<Pauli, 'x' | 'z'>): { inX: boolean; mask: number } {
  if (p.x) return { inX: true, mask: p.x & -p.x }
  return { inX: false, mask: p.z & -p.z }
}

interface Echelon {
  rows: { pauli: Pauli; inX: boolean; mask: number }[]
}

function reduce(e: Echelon, p: Pauli): Pauli {
  let v = p
  for (const row of e.rows) {
    if ((row.inX ? v.x : v.z) & row.mask) v = multiply(v, row.pauli)
  }
  return v
}

/** Membership in the group generated by the echelon rows, signs ignored. */
function inSpan(e: Echelon, p: Pick<Pauli, 'x' | 'z'>): boolean {
  const v = reduce(e, { x: p.x, z: p.z, sign: 0 })
  return v.x === 0 && v.z === 0
}

export interface DistanceResult {
  /** All Paulis of weight < lower were checked: none is a logical operator. */
  lower: number
  /** The weight of an actual logical operator that was found. */
  upper: number
  /** lower === upper. */
  exact: boolean
  /** A logical operator of weight `upper`. */
  witness: string
  /** How many Paulis the search looked at. */
  searched: number
}

export interface CodeAnalysis {
  n: number
  /** Number of independent generators. */
  rank: number
  k: number
  /** Indices (into the input) of generators that are products of earlier ones. */
  redundant: number[]
  /** Every generator is all-X or all-Z, as written. */
  css: boolean
  /** k anticommuting pairs. Which of a pair is called X is a convention. */
  logicals: { x: string; z: string }[]
  /** null when k = 0: a stabilizer state has no logical operators. */
  distance: DistanceResult | null
  /** Lightest non-identity element of the stabilizer group; null if not enumerated. */
  minStabilizerWeight: number | null
  /**
   * A stabilizer lighter than the distance exists, so distinct low-weight
   * errors share a syndrome and need no telling apart. null when unknown.
   */
  degenerate: boolean | null
}

export interface AnalyseOptions {
  /** Upper limit on Paulis examined by the distance search. */
  distanceBudget?: number
}

const DEFAULT_DISTANCE_BUDGET = 20_000_000

function choose(n: number, k: number): number {
  let c = 1
  for (let i = 0; i < k; i++) c = (c * (n - i)) / (i + 1)
  return c
}

/**
 * Analyse a list of stabilizer generators. Throws an Error a person can read
 * when the list is not a valid stabilizer group, naming the offending lines.
 */
export function analyseCode(lines: readonly string[], options: AnalyseOptions = {}): CodeAnalysis {
  const texts = lines.map((l) => l.trim()).filter((l) => l.length > 0)
  if (texts.length === 0) throw new Error('Enter at least one stabilizer generator.')

  const parsed = texts.map((t) => parsePauli(t))
  const n = parsed[0].n
  if (n < 1 || n > MAX_CODE_QUBITS) throw new Error(`Generators must act on between 1 and ${MAX_CODE_QUBITS} qubits.`)
  parsed.forEach((p, i) => {
    if (p.n !== n) throw new Error(`Generator ${i + 1} acts on ${p.n} qubits; the first acts on ${n}.`)
  })
  const gens = parsed.map((p) => p.pauli)

  for (let i = 0; i < gens.length; i++) {
    for (let j = i + 1; j < gens.length; j++) {
      if (!commutes(gens[i], gens[j])) {
        throw new Error(
          `Generators ${i + 1} and ${j + 1} anticommute (${texts[i]} and ${texts[j]}), so they have no common +1 eigenstate. This is not a stabilizer group.`,
        )
      }
    }
  }

  // Row-reduce. A generator that reduces to the identity is redundant; if it
  // reduces to MINUS the identity the group contains −I and stabilizes nothing.
  const echelon: Echelon = { rows: [] }
  const redundant: number[] = []
  gens.forEach((g, i) => {
    const v = reduce(echelon, g)
    if (v.x === 0 && v.z === 0) {
      if (v.sign) {
        throw new Error(`Generator ${i + 1} times earlier generators gives −I. A group containing −I stabilizes no state.`)
      }
      redundant.push(i)
    } else {
      echelon.rows.push({ pauli: v, ...pivotOf(v) })
    }
  })
  const rank = echelon.rows.length
  const k = n - rank
  const css = gens.every((g) => g.x === 0 || g.z === 0)

  // ── Logical operators: a symplectic basis of centralizer / stabilizer ──────
  const centralizer = centralizerBasis(
    echelon.rows.map((r) => r.pauli),
    n,
  )
  const pool = centralizer.map((p) => ({ ...p }))
  const pairs: { x: Pick<Pauli, 'x' | 'z'>; z: Pick<Pauli, 'x' | 'z'> }[] = []
  while (pool.length > 0) {
    const v = pool.shift()!
    const j = pool.findIndex((u) => !commutes(v, u))
    if (j < 0) continue // commutes with the whole centralizer: it is a stabilizer
    const w = pool.splice(j, 1)[0]
    for (const u of pool) {
      const hitsW = !commutes(u, w)
      const hitsV = !commutes(u, v)
      if (hitsW) {
        u.x ^= v.x
        u.z ^= v.z
      }
      if (hitsV) {
        u.x ^= w.x
        u.z ^= w.z
      }
    }
    // Convention: the Z-type member of a pair, if there is one, is logical Z.
    pairs.push(w.x === 0 || (v.x !== 0 && v.z === 0) ? { x: v, z: w } : { x: w, z: v })
  }

  const lighten = (p: Pick<Pauli, 'x' | 'z'>): Pick<Pauli, 'x' | 'z'> => {
    let best = { x: p.x, z: p.z }
    for (let improved = true; improved; ) {
      improved = false
      for (const row of echelon.rows) {
        const candidate = { x: best.x ^ row.pauli.x, z: best.z ^ row.pauli.z }
        if (weight(candidate) < weight(best)) {
          best = candidate
          improved = true
        }
      }
    }
    return best
  }
  const lightPairs = pairs.map((p) => ({ x: lighten(p.x), z: lighten(p.z) }))

  // ── Lightest stabilizer, by walking the whole group in Gray-code order ─────
  let minStabilizerWeight: number | null = null
  if (rank <= 20) {
    let x = 0
    let z = 0
    let min = Infinity
    for (let i = 1; i < 2 ** rank; i++) {
      const bit = 31 - Math.clz32(i & -i)
      x ^= echelon.rows[bit].pauli.x
      z ^= echelon.rows[bit].pauli.z
      const wt = popcount(x | z)
      if (wt < min) min = wt
    }
    minStabilizerWeight = min
  }

  // ── Distance ───────────────────────────────────────────────────────────────
  let distance: DistanceResult | null = null
  if (k > 0) {
    let upperOp = lightPairs[0].x
    for (const pair of lightPairs) {
      for (const op of [pair.x, pair.z]) if (weight(op) < weight(upperOp)) upperOp = op
    }
    distance = searchDistance(echelon, n, upperOp, options.distanceBudget ?? DEFAULT_DISTANCE_BUDGET)
  }

  return {
    n,
    rank,
    k,
    redundant,
    css,
    logicals: lightPairs.map((p) => ({ x: pauliString(p.x, n), z: pauliString(p.z, n) })),
    distance,
    minStabilizerWeight,
    degenerate:
      distance && distance.exact && minStabilizerWeight !== null ? minStabilizerWeight < distance.upper : null,
  }
}

/**
 * A basis for every Pauli (mod phase) that commutes with all the generators:
 * the null space of the generators under the symplectic form. Dimension 2n − r.
 */
function centralizerBasis(independent: readonly Pauli[], n: number): Pick<Pauli, 'x' | 'z'>[] {
  // Unknown v = (x_v | z_v). Generator g contributes the equation
  // z_g · x_v + x_g · z_v = 0, i.e. coefficients (z_g | x_g).
  const rows = independent.map((g) => ({ a: g.z, b: g.x })) // a multiplies x_v, b multiplies z_v
  const pivots: { inA: boolean; bit: number }[] = []
  let rank = 0
  for (let col = 0; col < 2 * n; col++) {
    const inA = col < n
    const mask = 1 << (inA ? col : col - n)
    let p = -1
    for (let i = rank; i < rows.length; i++) {
      if ((inA ? rows[i].a : rows[i].b) & mask) {
        p = i
        break
      }
    }
    if (p < 0) continue
    ;[rows[rank], rows[p]] = [rows[p], rows[rank]]
    for (let i = 0; i < rows.length; i++) {
      if (i !== rank && (inA ? rows[i].a : rows[i].b) & mask) {
        rows[i].a ^= rows[rank].a
        rows[i].b ^= rows[rank].b
      }
    }
    pivots.push({ inA, bit: inA ? col : col - n })
    rank++
  }

  const isPivot = (inA: boolean, bit: number) => pivots.some((p) => p.inA === inA && p.bit === bit)
  const basis: Pick<Pauli, 'x' | 'z'>[] = []
  for (let col = 0; col < 2 * n; col++) {
    const inA = col < n
    const bit = inA ? col : col - n
    if (isPivot(inA, bit)) continue
    // Free variable set to 1; each pivot variable takes whatever its row needs.
    const v = { x: inA ? 1 << bit : 0, z: inA ? 0 : 1 << bit }
    pivots.forEach((pv, i) => {
      if ((inA ? rows[i].a : rows[i].b) & (1 << bit)) {
        if (pv.inA) v.x |= 1 << pv.bit
        else v.z |= 1 << pv.bit
      }
    })
    basis.push(v)
  }
  return basis
}

/**
 * Minimum weight of a Pauli that commutes with every stabilizer but is not one.
 * Weights are tried in increasing order; each candidate's syndrome is built up
 * by XOR as qubits are added, so a candidate costs O(1).
 */
function searchDistance(
  echelon: Echelon,
  n: number,
  knownLogical: Pick<Pauli, 'x' | 'z'>,
  budget: number,
): DistanceResult {
  const gens = echelon.rows.map((r) => r.pauli)
  const syndromeOfSingle = (p: Pick<Pauli, 'x' | 'z'>): number => {
    let s = 0
    gens.forEach((g, i) => {
      if (!commutes(g, p)) s |= 1 << i
    })
    return s
  }
  const synX = Array.from({ length: n }, (_, q) => syndromeOfSingle({ x: 1 << q, z: 0 }))
  const synZ = Array.from({ length: n }, (_, q) => syndromeOfSingle({ x: 0, z: 1 << q }))

  const upper = weight(knownLogical)
  let searched = 0
  let found: Pick<Pauli, 'x' | 'z'> | null = null

  const visit = (start: number, remaining: number, x: number, z: number, syn: number): void => {
    if (remaining === 0) {
      searched++
      if (syn === 0 && !inSpan(echelon, { x, z })) found = { x, z }
      return
    }
    for (let q = start; q <= n - remaining && !found; q++) {
      const m = 1 << q
      visit(q + 1, remaining - 1, x | m, z, syn ^ synX[q])
      if (found) return
      visit(q + 1, remaining - 1, x, z | m, syn ^ synZ[q])
      if (found) return
      visit(q + 1, remaining - 1, x | m, z | m, syn ^ synX[q] ^ synZ[q])
    }
  }

  for (let w = 1; w < upper; w++) {
    const cost = choose(n, w) * 3 ** w
    if (searched + cost > budget) {
      return { lower: w, upper, exact: false, witness: pauliString(knownLogical, n), searched }
    }
    visit(0, w, 0, 0, 0)
    if (found) return { lower: w, upper: w, exact: true, witness: pauliString(found, n), searched }
  }
  return { lower: upper, upper, exact: true, witness: pauliString(knownLogical, n), searched }
}

/**
 * The syndrome an error produces: one bit per generator AS WRITTEN (redundant
 * ones included), 1 where the error anticommutes with it.
 */
export function syndromeOf(generators: readonly string[], error: string): string {
  const e = parsePauli(error).pauli
  return generators.map((g) => (commutes(parsePauli(g).pauli, e) ? '0' : '1')).join('')
}

