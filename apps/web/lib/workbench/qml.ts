export type DatasetId = 'moons' | 'circles' | 'quantum'

export const DATASET_IDS: readonly DatasetId[] = ['moons', 'circles', 'quantum']

/** Two features per row, labels in {−1, +1}. */
export interface Dataset {
  id: DatasetId
  n: number
  /** Row-major, length 2n. */
  x: Float64Array
  /** Length n, each entry −1 or +1. */
  y: Int8Array
}

/**
 * Two interleaving half-circles (scikit-learn's make_moons): the upper arc is
 * the unit semicircle, the lower arc is its mirror shifted right by 1 and down
 * by ½, plus isotropic Gaussian noise. Not linearly separable — a straight line
 * tops out around 85–88% — but a cubic polynomial separates it almost cleanly.
 */
export function makeMoons(n: number, noise: number, rng: Rng): Dataset {
  const x = new Float64Array(2 * n)
  const y = new Int8Array(n)
  const half = Math.floor(n / 2)
  for (let i = 0; i < n; i++) {
    const upper = i < half
    const t = (upper ? i / Math.max(1, half - 1) : (i - half) / Math.max(1, n - half - 1)) * Math.PI
    const px = upper ? Math.cos(t) : 1 - Math.cos(t)
    const py = upper ? Math.sin(t) : 0.5 - Math.sin(t)
    x[2 * i] = px + noise * gaussian(rng)
    x[2 * i + 1] = py + noise * gaussian(rng)
    y[i] = upper ? 1 : -1
  }
  return shuffleRows({ id: 'moons', n, x, y }, rng)
}

/**
 * Concentric circles (make_circles): an outer unit circle and an inner one of
 * radius `factor`, both with Gaussian noise. No straight line does better than
 * chance; the radius is a quadratic feature, so a polynomial fit is exact.
 */
export function makeCircles(n: number, noise: number, factor: number, rng: Rng): Dataset {
  const x = new Float64Array(2 * n)
  const y = new Int8Array(n)
  const half = Math.floor(n / 2)
  for (let i = 0; i < n; i++) {
    const outer = i < half
    const k = outer ? i : i - half
    const m = outer ? half : n - half
    const t = (2 * Math.PI * k) / m
    const r = outer ? 1 : factor
    x[2 * i] = r * Math.cos(t) + noise * gaussian(rng)
    x[2 * i + 1] = r * Math.sin(t) + noise * gaussian(rng)
    y[i] = outer ? 1 : -1
  }
  return shuffleRows({ id: 'circles', n, x, y }, rng)
}

/** The hidden circuit that labels the quantum dataset. Fixed so the page and the tests agree. */
export const HIDDEN_CIRCUIT: VqcConfig = { numQubits: 2, layers: 3, encodingScale: Math.PI / 2 }
export const HIDDEN_CIRCUIT_SEED = 2026

/** Trainable angles of the hidden circuit, drawn once from the fixed seed. */
export function hiddenCircuitParams(): Float64Array {
  const rng = seededRng(HIDDEN_CIRCUIT_SEED)
  const theta = new Float64Array(vqcParamCount(HIDDEN_CIRCUIT))
  for (let i = 0; i < theta.length; i++) theta[i] = 2 * Math.PI * rng()
  return theta
}

/**
 * Inputs uniform on [−√3, √3]² (mean 0, unit variance, so standardisation is
 * close to the identity and the student circuit sees the same angles the
 * hidden one did); labels are the sign of the hidden circuit's ⟨Z⟩ relative to
 * its median over the sample, which balances the classes exactly.
 */
export function makeQuantumDataset(n: number, rng: Rng): Dataset {
  const x = new Float64Array(2 * n)
  const y = new Int8Array(n)
  const theta = hiddenCircuitParams()
  const scores = new Float64Array(n)
  const half = Math.sqrt(3)
  for (let i = 0; i < n; i++) {
    x[2 * i] = (2 * rng() - 1) * half
    x[2 * i + 1] = (2 * rng() - 1) * half
    scores[i] = vqcExpectation(HIDDEN_CIRCUIT, theta, x[2 * i], x[2 * i + 1])
  }
  const sorted = Array.from(scores).sort((a, b) => a - b)
  const median = sorted[Math.floor(n / 2)]
  for (let i = 0; i < n; i++) y[i] = scores[i] >= median ? 1 : -1
  return { id: 'quantum', n, x, y }
}

function shuffleRows(ds: Dataset, rng: Rng): Dataset {
  const order = Array.from({ length: ds.n }, (_, i) => i)
  for (let i = order.length - 1; i > 0; i--) {
    const j = Math.floor(rng() * (i + 1))
    ;[order[i], order[j]] = [order[j], order[i]]
  }
  const x = new Float64Array(2 * ds.n)
  const y = new Int8Array(ds.n)
  order.forEach((src, dst) => {
    x[2 * dst] = ds.x[2 * src]
    x[2 * dst + 1] = ds.x[2 * src + 1]
    y[dst] = ds.y[src]
  })
  return { ...ds, x, y }
}

export const DATASET_DEFAULT_SIZE = 300

export function makeDataset(id: DatasetId, seed: number, n = DATASET_DEFAULT_SIZE): Dataset {
  const rng = seededRng(seed)
  switch (id) {
    case 'moons':
      return makeMoons(n, 0.15, rng)
    case 'circles':
      return makeCircles(n, 0.08, 0.5, rng)
    case 'quantum':
      return makeQuantumDataset(n, rng)
  }
}

// ────────────────────────────────────────────────────────────
// Train / test split, standardisation
// ────────────────────────────────────────────────────────────

export interface Split {
  trainX: Float64Array
  trainY: Int8Array
  testX: Float64Array
  testY: Int8Array
  nTrain: number
  nTest: number
  /** Per-feature mean and standard deviation of the TRAINING rows, applied to both halves. */
  mean: [number, number]
  std: [number, number]
}

/**
 * Held-out split. The first `1 − testFraction` of the (already shuffled) rows
 * train, the rest are never seen by any optimiser. Features are z-scored using
 * training statistics only — the test rows get the training mean and std, as
 * they would in production, so no information leaks backward.
 */
export function splitDataset(ds: Dataset, testFraction = 0.3): Split {
  const nTest = Math.max(1, Math.round(ds.n * testFraction))
  const nTrain = ds.n - nTest
  const mean: [number, number] = [0, 0]
  const std: [number, number] = [0, 0]
  for (let f = 0; f < 2; f++) {
    let s = 0
    for (let i = 0; i < nTrain; i++) s += ds.x[2 * i + f]
    mean[f] = s / nTrain
    let v = 0
    for (let i = 0; i < nTrain; i++) v += (ds.x[2 * i + f] - mean[f]) ** 2
    std[f] = Math.sqrt(v / nTrain) || 1
  }
  const z = (i: number, f: number) => (ds.x[2 * i + f] - mean[f]) / std[f]
  const trainX = new Float64Array(2 * nTrain)
  const testX = new Float64Array(2 * nTest)
  for (let i = 0; i < nTrain; i++) {
    trainX[2 * i] = z(i, 0)
    trainX[2 * i + 1] = z(i, 1)
  }
  for (let i = 0; i < nTest; i++) {
    testX[2 * i] = z(nTrain + i, 0)
    testX[2 * i + 1] = z(nTrain + i, 1)
  }
  return {
    trainX,
    trainY: ds.y.slice(0, nTrain),
    testX,
    testY: ds.y.slice(nTrain),
    nTrain,
    nTest,
    mean,
    std,
  }
}

// ────────────────────────────────────────────────────────────
// Cost meter
// ────────────────────────────────────────────────────────────

export interface Cost {
  /** End-to-end executions of a quantum circuit. */
  circuitEvals: number
  /** Approximate classical floating-point operations. */
  flops: number
}

export class CostMeter implements Cost {
  circuitEvals = 0
  flops = 0
  snapshot(): Cost {
    return { circuitEvals: this.circuitEvals, flops: this.flops }
  }
}

// ────────────────────────────────────────────────────────────
// The variational quantum classifier
// ────────────────────────────────────────────────────────────

export interface VqcConfig {
  numQubits: 2 | 3 | 4
  layers: number
  /** κ — radians of rotation per standardised unit of a feature. */
  encodingScale: number
}

export const VQC_DEFAULT: VqcConfig = { numQubits: 2, layers: 3, encodingScale: Math.PI / 2 }

/** Two trainable angles (RY, RZ) per qubit per layer. */
export function vqcParamCount(cfg: VqcConfig): number {
  return 2 * cfg.numQubits * cfg.layers
}

/**
 * ⟨Z⟩ on the last qubit after the circuit described in the header, with the
 * given trainable angles and the two (standardised) features. One call is one
 * circuit evaluation; the meter, when supplied, is charged for it.
 */
export function vqcExpectation(
  cfg: VqcConfig,
  theta: ArrayLike<number>,
  x0: number,
  x1: number,
  meter?: CostMeter,
): number {
  const n = cfg.numQubits
  const sv = new StateVector(n)
  const dim = 1 << n
  let k = 0
  let flops = 0
  for (let layer = 0; layer < cfg.layers; layer++) {
    for (let q = 0; q < n; q++) {
      sv.applySingle('RY', q, cfg.encodingScale * (q % 2 === 0 ? x0 : x1))
      flops += 16 * dim
    }
    for (let q = 0; q < n; q++) {
      sv.applySingle('RY', q, theta[k++])
      sv.applySingle('RZ', q, theta[k++])
      flops += 32 * dim
    }
    for (let q = 0; q < n - 1; q++) {
      sv.applyControlled('X', [q], q + 1)
      flops += 8 * dim
    }
  }
  if (meter) {
    meter.circuitEvals += 1
    meter.flops += flops + 4 * dim
  }
  return 1 - 2 * sv.qubitProbability(n - 1)
}

/** Full classifier parameters: the circuit angles plus the classical readout scale and bias. */
export interface VqcParams {
  theta: Float64Array
  w: number
  b: number
}

/** Numerically safe binary cross-entropy for a logit s and a label y ∈ {−1, +1}. */
function logLoss(s: number, y: number): number {
  // log(1 + e^{−y·s}) without overflow.
  const z = -y * s
  return z > 0 ? z + Math.log1p(Math.exp(-z)) : Math.log1p(Math.exp(z))
}

/**
 * Mean cross-entropy of the VQC over the given rows, computed by evaluating the
 * circuit once per row. This is the function the gradient below differentiates
 * and the function the finite-difference test differentiates numerically; the
 * two share only this code.
 */
export function vqcLoss(
  cfg: VqcConfig,
  p: VqcParams,
  X: Float64Array,
  Y: Int8Array,
  rows: ArrayLike<number>,
  meter?: CostMeter,
): number {
  let total = 0
  for (let r = 0; r < rows.length; r++) {
    const i = rows[r]
    const f = vqcExpectation(cfg, p.theta, X[2 * i], X[2 * i + 1], meter)
    total += logLoss(p.w * f + p.b, Y[i])
  }
  return total / rows.length
}

export interface VqcGradient {
  loss: number
  theta: Float64Array
  w: number
  b: number
}

/**
 * Gradient of `vqcLoss` by the parameter-shift rule. For each row: one forward
 * evaluation for the loss, then two shifted evaluations per angle — so
 * (2P + 1)·|rows| circuit runs per call, every one of which is charged to the
 * meter. That count is the honest price of a quantum gradient.
 */
export function vqcGradient(
  cfg: VqcConfig,
  p: VqcParams,
  X: Float64Array,
  Y: Int8Array,
  rows: ArrayLike<number>,
  meter?: CostMeter,
): VqcGradient {
  const P = p.theta.length
  const gTheta = new Float64Array(P)
  let gW = 0
  let gB = 0
  let loss = 0
  const shifted = new Float64Array(p.theta)
  const m = rows.length
  for (let r = 0; r < m; r++) {
    const i = rows[r]
    const x0 = X[2 * i]
    const x1 = X[2 * i + 1]
    const f = vqcExpectation(cfg, p.theta, x0, x1, meter)
    const s = p.w * f + p.b
    const y01 = Y[i] > 0 ? 1 : 0
    loss += logLoss(s, Y[i])
    const dLds = sigmoid(s) - y01
    gW += dLds * f
    gB += dLds
    const chain = dLds * p.w
    for (let k = 0; k < P; k++) {
      shifted[k] = p.theta[k] + Math.PI / 2
      const plus = vqcExpectation(cfg, shifted, x0, x1, meter)
      shifted[k] = p.theta[k] - Math.PI / 2
      const minus = vqcExpectation(cfg, shifted, x0, x1, meter)
      shifted[k] = p.theta[k]
      gTheta[k] += chain * 0.5 * (plus - minus)
    }
  }
  for (let k = 0; k < P; k++) gTheta[k] /= m
  if (meter) meter.flops += m * (4 * P + 12)
  return { loss: loss / m, theta: gTheta, w: gW / m, b: gB / m }
}

// ────────────────────────────────────────────────────────────
// Adam, shared by the VQC and the MLP — lib/numerics/nn's, the same update
// the surface-code decoders and the ZNE extrapolator use.
// ────────────────────────────────────────────────────────────

/** One Adam step on a packed parameter vector from the gradient in `p.grad`. Returns the flops it spent. */
function adamUpdate(p: Param, step: number, lr: number): number {
  adamStep([p], step, { lr })
  return 12 * p.value.length
}

