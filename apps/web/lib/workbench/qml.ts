/**
 * lib/workbench/qml.ts — the numerics behind /workbench/qml-check.
 *
 * ── What this module is for ─────────────────────────────────────────────────────
 *
 * A fair, small-scale fight between a variational quantum classifier (VQC) and
 * two classical baselines — a properly fitted logistic regression and a small
 * multilayer perceptron — on three two-feature binary datasets. Two of the
 * datasets are the classical toy sets every ML tutorial uses (moons, circles);
 * the third has labels produced by MEASURING A HIDDEN QUANTUM CIRCUIT on the
 * encoded input. The tool's whole point is that the ranking flips between them,
 * and that the reader can see why.
 *
 * Everything here is deterministic given a seed, runs with no DOM, and is
 * structured as resumable *trainers* (`Trainer.step()` advances one optimiser
 * step) so the same code can be driven from a Web Worker, from a
 * requestAnimationFrame loop, from a test, or from the MCP server. Nothing in
 * this file ever blocks for longer than one step.
 *
 * ── The quantum model ───────────────────────────────────────────────────────────
 *
 * Angle encoding with data re-uploading, a hardware-efficient ansatz, ⟨Z⟩
 * readout. For n qubits, L layers and the two features x = (x₀, x₁):
 *
 *     for ℓ in 1..L:
 *         RY(κ·x_{q mod 2})  on every qubit q          (encoding, re-uploaded)
 *         RY(θ) RZ(θ)        on every qubit q          (2 trainable angles each)
 *         CX(q, q+1)         for q = 0..n−2            (a ladder of CNOTs)
 *     f(x, θ) = ⟨Z⟩ on qubit n−1
 *
 * The readout qubit is the last one because it is the final CNOT's TARGET —
 * measuring the control instead would make the last layer's entangler a no-op
 * (Z on a control commutes with CNOT). The circuit is simulated exactly with
 * the statevector engine in lib/quantum.ts; `CostMeter` counts how many times
 * it was run, because on hardware every one of those runs is thousands of
 * shots and that — not the arithmetic — is the cost that matters.
 *
 * The classifier is p(y = 1 | x) = σ(w·f(x, θ) + b). The two classical numbers
 * w and b are a threshold and a scale on the expectation value; every quantum
 * model in the literature has an equivalent, and without them a readout in
 * [−1, 1] can never express a confident probability.
 *
 * Gradients with respect to θ use the PARAMETER-SHIFT RULE, which is exact for
 * gates generated by a Pauli: ∂⟨M⟩/∂θ = [⟨M⟩(θ + π/2) − ⟨M⟩(θ − π/2)] / 2. Two
 * extra circuit evaluations per parameter per data point — that factor is why
 * `circuitEvals` in the results grows the way it does, and why training a
 * quantum model is slow, not fast. `qml.test.ts` checks the rule against
 * central finite differences of the loss, which share no code with it.
 *
 * ── The quantum-generated dataset ───────────────────────────────────────────────
 *
 * Inputs are uniform on the same standardised square the other datasets end up
 * on; labels are sign(f(x, θ*) − median) for a FIXED, seeded θ* on a 2-qubit,
 * 3-layer circuit of the family above. The VQC wins here for an honest and
 * slightly deflating reason: the labelling function is in its hypothesis class
 * by construction. A rotation-encoded circuit outputs a Fourier series in x
 * whose frequencies the encoding fixes (Schuld, Sweke & Meyer 2021), so a
 * circuit that re-uploads x three times contains frequencies up to 3 in each
 * feature — a bumpy, periodic decision surface that a degree-3 polynomial
 * logistic regression cannot follow and a small MLP needs many more steps to
 * approximate. That is the 2026 evidence in miniature: advantages have been
 * shown for QUANTUM data (Huang et al. 2021–22), none for classical data.
 *
 * ── Cost accounting ─────────────────────────────────────────────────────────────
 *
 *   circuitEvals   how many times a quantum circuit was executed end to end.
 *                  The hardware-relevant number. Classical models: 0.
 *   flops          approximate floating-point operations the CLASSICAL machine
 *                  performed — for the VQC, that is what the statevector
 *                  simulator did, counted per gate as 16·2ⁿ (single-qubit) and
 *                  8·2ⁿ (CNOT). It is what your laptop actually spent, and it
 *                  is the reason a simulated VQC is not evidence of anything.
 *
 * Both are counted from the operations performed, not estimated after the
 * fact, so the same training run on a different budget reports different
 * numbers.
 */

