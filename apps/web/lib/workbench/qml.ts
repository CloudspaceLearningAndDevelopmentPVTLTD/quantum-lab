export interface ComparisonConfig {
  dataset: DatasetId
  seed: number
  /** Rows generated before the split. */
  size: number
  vqc: VqcConfig
  vqcOptions: VqcOptions
  mlp: MlpOptions
  logreg: LogRegOptions
}

export const COMPARISON_DEFAULT: ComparisonConfig = {
  dataset: 'moons',
  seed: 7,
  size: DATASET_DEFAULT_SIZE,
  vqc: VQC_DEFAULT,
  vqcOptions: VQC_OPTIONS_DEFAULT,
  mlp: MLP_DEFAULT,
  logreg: LOGREG_DEFAULT,
}

export interface Comparison {
  split: Split
  trainers: Record<ModelId, Trainer>
}

/** Builds the dataset, the split and the three trainers. Nothing is trained yet. */
export function prepareComparison(cfg: ComparisonConfig): Comparison {
  const ds = makeDataset(cfg.dataset, cfg.seed, cfg.size)
  const split = splitDataset(ds)
  // Separate streams so changing one model's options does not reseed another's.
  const mlpRng = seededRng(cfg.seed * 31 + 1)
  const vqcRng = seededRng(cfg.seed * 31 + 2)
  return {
    split,
    trainers: {
      logreg: createLogRegTrainer(split, cfg.logreg),
      mlp: createMlpTrainer(split, cfg.mlp, mlpRng),
      vqc: createVqcTrainer(split, cfg.vqc, cfg.vqcOptions, vqcRng),
    },
  }
}

/** Train every model to its budget, synchronously. Tests and the MCP tool use this. */
export function runComparison(cfg: ComparisonConfig): Record<ModelId, ModelReport> {
  const { trainers } = prepareComparison(cfg)
  for (const id of MODEL_IDS) {
    const t = trainers[id]
    while (!t.step()) {
      /* until the trainer says it is done */
    }
  }
  return {
    logreg: trainers.logreg.report(),
    mlp: trainers.mlp.report(),
    vqc: trainers.vqc.report(),
  }
}

/**
 * Decision surface on a res×res grid over the standardised square [−lim, lim]²,
 * row-major from the bottom-left. Scores are signed; the page paints sign and
 * magnitude. For the VQC this is res² circuit runs and IS charged to its meter.
 */
export function decisionGrid(t: Trainer, res: number, lim: number): Float32Array {
  const out = new Float32Array(res * res)
  for (let j = 0; j < res; j++) {
    const x1 = -lim + (2 * lim * (j + 0.5)) / res
    for (let i = 0; i < res; i++) {
      const x0 = -lim + (2 * lim * (i + 0.5)) / res
      out[j * res + i] = t.score(x0, x1)
    }
  }
  return out
}
