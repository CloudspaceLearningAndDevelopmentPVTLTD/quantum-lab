#!/usr/bin/env bash
# Regenerate supabase/migrations/ from the canonical schema files.
#
# The schema lives in supabase/schema*.sql, written to be pasted into the SQL
# editor and idempotent. The Supabase CLI applies migrations from
# supabase/migrations/<timestamp>_<name>.sql instead, so this script copies
# each schema file there under a fixed, ordered timestamp. Fixed on purpose:
# the CLI records which migration *names* it has applied, and a regenerated
# file with the same name is a no-op, while a new timestamp would re-run it.
#
# Order matters — every later file reuses helpers schema.sql defines.
#
#   bash scripts/supabase-migrations.sh      # regenerate
#   supabase login && supabase link --project-ref <ref>
#   supabase db push                         # apply to the linked project
set -euo pipefail
cd "$(dirname "${BASH_SOURCE[0]}")/.."
OUT=supabase/migrations
mkdir -p "$OUT"
i=0
for pair in \
  "schema.sql:core" \
  "schema-billing.sql:billing" \
  "schema-exams.sql:exams" \
  "schema-orgs.sql:orgs" \
  "schema-competitions.sql:competitions" \
  "schema-email.sql:email" \
  "schema-integrations.sql:integrations" \
  "schema-platform.sql:platform" \
  "schema-experiments.sql:experiments" \
  "schema-analytics.sql:analytics"   "schema-sessions.sql:sessions"   "schema-runs.sql:runs"   "schema-budgets.sql:budgets"   "schema-byok.sql:byok"   "schema-hardening.sql:hardening"; do
  src="supabase/${pair%%:*}"; name="${pair##*:}"
  i=$((i + 1))
  # Zero-padded to 2 digits: a bare "${i}" sorts "...00010" before
  # "...000009" once i reaches double digits (string comparison, not
  # numeric), which silently reordered every migration after the 9th
  # entry the first time this list grew past nine files.
  dest="$OUT/$(printf '2026090100%04d' "$i")_${name}.sql"
  {
    echo "-- GENERATED by scripts/supabase-migrations.sh from $src — edit that file, then regenerate."
    echo
    cat "$src"
  } > "$dest"
  echo "wrote $dest"
done
