"""Cross-check the browser simulator against Qiskit.

``apps/web/lib/quantum.ts`` is a hand-written statevector simulator; this
service runs the same circuits through Qiskit. The product shows both answers
to the same learner — the browser draws the state, this service runs it on a
backend — so a disagreement is a wrong claim on screen, not an internal
detail. Nothing in the app compares them. These tests do.

The fixture ``tests/data/js_statevectors.json`` is generated by
``apps/web/lib/quantum.crosscheck.test.ts`` (see the header there for the
regeneration command) and holds, per circuit: the OpenQASM the web app
exports, and the amplitudes the JS simulator computes for it.

Conventions being checked, not assumed:

* qubit 0 is the least significant bit, so basis index ``i`` has qubit ``q``
  set when ``(i >> q) & 1``. Qiskit uses the same index order, which is why
  the amplitude arrays can be compared element-by-element with no reordering.
* labels print MSB-first, ``format(index, "0{n}b")``.

Global phase is NOT modded out. Both implementations are expected to produce
the same phase, including the ``rz`` convention (``e^{-i0/2}`` on |0>, not
``u1``'s ``1``). If a future change only differs by a global phase, that is
still a change worth seeing, and the failure message says which case moved.

The QASM here is parsed **unmodified**. It used to be rewritten first, by a
``_fold_angles`` helper that replaced ``ry(pi/3)`` with a decimal, because
``qiskit-qasm3-import`` was not a dependency and nothing else in the service
could read a pi expression. That helper is gone: the package is required now
(see requirements.txt and
:func:`test_the_qasm3_importer_is_a_required_dependency`), so these tests
exercise the same bytes the hardware page posts.

This file only covers the twelve circuits frozen into the fixture. The random
spread — hundreds of circuits, generated fresh each run and executed through
the real TypeScript module — lives in ``tests/test_js_random_crosscheck.py``.
"""

from __future__ import annotations

import json
import math
from pathlib import Path
from typing import Any

import pytest

from app.quantum.runner import parse_qasm

FIXTURE = Path(__file__).parent / "data" / "js_statevectors.json"
REQUIREMENTS = Path(__file__).resolve().parents[1] / "requirements.txt"

# Measured worst case across the whole fixture, parsing the app's exported QASM
# unmodified: 6.661e-16 (preset:grover2). The bound is seven orders of magnitude
# looser so that floating-point reassociation cannot fail the suite, and still
# tight enough that a gate-order or sign error cannot hide under it.
TOLERANCE = 1e-9


def _load_cases() -> list[dict[str, Any]]:
    """Read the fixture written by the TypeScript test.

    Returns:
        The list of circuit cases.
    """
    with FIXTURE.open(encoding="utf-8") as handle:
        return list(json.load(handle)["cases"])


CASES = _load_cases()
CASE_IDS = [case["id"] for case in CASES]


def _qiskit_statevector(qasm: str) -> list[complex]:
    """Simulate a circuit with Qiskit, ignoring measurement and barriers.

    Args:
        qasm: OpenQASM 3 source.

    Returns:
        Amplitudes in the same index order the JS simulator uses.
    """
    from qiskit import QuantumCircuit
    from qiskit.quantum_info import Statevector

    circuit = parse_qasm(qasm)
    unitary = QuantumCircuit(circuit.num_qubits)
    for instruction in circuit.data:
        if instruction.operation.name in ("measure", "barrier", "reset"):
            continue
        unitary.append(
            instruction.operation,
            [circuit.find_bit(qubit).index for qubit in instruction.qubits],
        )
    return list(Statevector.from_instruction(unitary).data)


@pytest.mark.parametrize("case", CASES, ids=CASE_IDS)
def test_js_statevector_matches_qiskit(case: dict[str, Any]) -> None:
    """Every amplitude from lib/quantum.ts matches Qiskit's, phase included."""
    qiskit_amps = _qiskit_statevector(case["qasm"])
    js_amps = [complex(re_, im) for re_, im in case["amplitudes"]]

    assert len(qiskit_amps) == len(js_amps) == 2 ** case["numQubits"]
    worst = max(abs(a - b) for a, b in zip(js_amps, qiskit_amps))
    assert worst < TOLERANCE, (
        f"{case['id']}: JS and Qiskit disagree by {worst:.3e}.\n"
        f"  js     = {[f'{a:.6f}' for a in js_amps]}\n"
        f"  qiskit = {[f'{a:.6f}' for a in qiskit_amps]}"
    )


@pytest.mark.parametrize("case", CASES, ids=CASE_IDS)
def test_labels_follow_the_shared_bit_convention(case: dict[str, Any]) -> None:
    """The JS labels are MSB-first over a qubit-0-is-LSB index, like Qiskit."""
    width = case["numQubits"]
    assert case["labels"] == [format(i, f"0{width}b") for i in range(2**width)]


def test_x_on_qubit_zero_lands_on_index_one_in_both_engines() -> None:
    """The single cheapest way to catch a mirrored register.

    An X on qubit 0 of a 3-qubit register must put all the probability on
    basis index 1, labelled "001". If either engine ever reports index 4 /
    "100", its bit order has flipped and every multi-qubit result in the
    product is mirrored.
    """
    qasm = (
        'OPENQASM 3.0;\ninclude "stdgates.inc";\n\n'
        "qubit[3] q;\nbit[3] c;\n\nx q[0];\n\nc = measure q;\n"
    )
    amps = _qiskit_statevector(qasm)
    assert abs(amps[1]) == pytest.approx(1.0, abs=1e-12)
    assert abs(amps[4]) == pytest.approx(0.0, abs=1e-12)

    case = next(c for c in CASES if c["id"] == "asymmetric-cx")
    # Same circuit's first two gates: X on q0 then CX(q0 -> q2) gives |101>,
    # basis index 5, in the JS fixture too.
    assert "x q[0];" in case["qasm"].splitlines()


def _importer_available() -> bool:
    """Report whether ``qiskit_qasm3_import`` is installed."""
    import importlib.util

    return importlib.util.find_spec("qiskit_qasm3_import") is not None


def test_the_qasm3_importer_is_a_required_dependency() -> None:
    """CLOSED GAP, pinned so it cannot silently reopen.

    ``apps/web/lib/quantum.ts`` exports rotation angles as exact fractions of
    pi (``ry(pi/3)``) — the same thing Qiskit's own ``qasm3.dumps`` emits — and
    ``app/hardware/page.tsx`` posts that text straight to this service. Without
    ``qiskit_qasm3_import`` every parser here rejects it: ``qasm3.loads`` has
    nothing to delegate to, the native importer raises "unhandled expression
    for floating-point constant" on a bare ``pi``, and the QASM 2 reader
    refuses the 3.0 header. The teleportation preset could not be run or costed.

    Both halves are asserted, because either one alone is a test that would
    pass with the fix reverted: the package must be importable HERE (so this
    environment is really exercising the importer path), and it must be a
    non-optional line in requirements.txt (so a fresh deployment gets it too —
    the file lists four other providers as commented-out extras, and dropping
    this one into that block would restore the bug with the suite still green).
    """
    assert _importer_available(), (
        "qiskit_qasm3_import is not installed in this environment, so pi-angle "
        "circuits from the web app cannot be parsed. Run "
        "'pip install -r services/api/requirements.txt'."
    )

    lines = [
        line.split("#", 1)[0].strip()
        for line in REQUIREMENTS.read_text(encoding="utf-8").splitlines()
    ]
    assert any(line.startswith("qiskit-qasm3-import") for line in lines), (
        "qiskit-qasm3-import must stay an uncommented requirement; commenting it "
        "out re-breaks every pi-angle circuit the web app exports."
    )


def test_every_angle_form_the_web_app_emits_parses() -> None:
    """The exact output space of ``formatAngle`` in apps/web/lib/quantum.ts.

    That function emits ``0``, ``pi``, ``-pi``, ``<n>*pi``, ``pi/<d>``,
    ``<n>*pi/<d>`` and a shortest-round-trip decimal, for d in
    {1,2,3,4,6,8,12,16}. Each form is checked against the value the JS side
    computes for it, so a parser that accepts the text but folds the
    arithmetic differently (``2*pi/3`` read as ``2*(pi/3)`` vs ``(2*pi)/3`` —
    the same here, but not for every expression) is caught rather than assumed.
    """
    header = 'OPENQASM 3.0;\ninclude "stdgates.inc";\n\nqubit[1] q;\nbit[1] c;\n\n'
    expected = {
        "0": 0.0,
        "pi": math.pi,
        "-pi": -math.pi,
        "3*pi": 3 * math.pi,
        "-2*pi": -2 * math.pi,
        "pi/2": math.pi / 2,
        "pi/3": math.pi / 3,
        "pi/4": math.pi / 4,
        "pi/6": math.pi / 6,
        "pi/8": math.pi / 8,
        "pi/12": math.pi / 12,
        "pi/16": math.pi / 16,
        "2*pi/3": 2 * math.pi / 3,
        "-3*pi/4": -3 * math.pi / 4,
        "0.7391": 0.7391,
        "-1.234567890123": -1.234567890123,
    }
    for text, value in expected.items():
        circuit = parse_qasm(f"{header}rz({text}) q[0];\n\nc = measure q;\n")
        angle = float(circuit.data[0].operation.params[0])
        assert angle == pytest.approx(value, abs=1e-12), f"rz({text}) parsed as {angle}"


@pytest.mark.parametrize("case", CASES, ids=CASE_IDS)
def test_the_apps_exported_qasm_parses_unmodified(case: dict[str, Any]) -> None:
    """Every circuit the web app exports is accepted byte-for-byte.

    This is the round trip the hardware page actually performs: toQasm() in the
    browser, POST, parse_qasm() here. No rewriting, no angle folding — if this
    passes, /api/hardware/estimate and /api/circuits/run can serve the circuit.
    """
    circuit = parse_qasm(case["qasm"])
    assert circuit.num_qubits == case["numQubits"]


@pytest.mark.parametrize("case", CASES, ids=CASE_IDS)
def test_the_apps_exported_qasm_runs_and_costs(case: dict[str, Any]) -> None:
    """The two things the gap actually blocked: running and pricing a circuit.

    ``preset:teleport`` is the case named in the original bug report; it is in
    CASES, so this covers it plus every other exported circuit. A parse test
    alone would not catch a runner or estimator that re-parses through a
    different path.
    """
    from app.quantum.runner import run_circuit
    from app.quantum.transpile import analyse_circuit, estimate_cost

    result = run_circuit(case["qasm"], shots=64)
    assert sum(result["counts"].values()) == 64
    assert result["num_qubits"] == case["numQubits"]

    analysis = analyse_circuit(case["qasm"])
    assert analysis["num_qubits"] == case["numQubits"]
    cost = estimate_cost("ionq_aria", 64, int(analysis["num_qubits"]))
    assert cost["estimated_total"] > 0


