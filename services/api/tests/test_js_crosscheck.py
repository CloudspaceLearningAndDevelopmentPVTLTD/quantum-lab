def _pennylane_available() -> bool:
    """Report whether PennyLane and the lightning device are both installed."""
    import importlib.util

    return all(
        importlib.util.find_spec(name) is not None
        for name in ("pennylane", "pennylane_lightning")
    )


@pytest.mark.skipif(not _pennylane_available(), reason="pennylane/lightning not installed")
@pytest.mark.parametrize("case", CASES, ids=CASE_IDS)
def test_pennylane_statevector_matches_the_js_simulator(case: dict[str, Any]) -> None:
    """The wire-order reversal in statevector_with_pennylane is correct.

    PennyLane indexes amplitudes with wire 0 as the MOST significant bit, the
    opposite of this project. ``statevector_with_pennylane`` fixes that by
    reversing the bits of every index. A symmetric circuit cannot detect a
    mistake there, so the fixture deliberately includes asymmetric ones
    (``asymmetric-cx``, ``toffoli-and-swap``, ``five-qubit-free-tier``): if the
    reversal is dropped, those amplitudes land in mirrored slots and this test
    fails while Bell and GHZ still pass.
    """
    from app.quantum.pennylane_runner import statevector_with_pennylane

    result = statevector_with_pennylane(case["qasm"])
    pennylane_amps = [complex(a["re"], a["im"]) for a in result["amplitudes"]]
    js_amps = [complex(re_, im) for re_, im in case["amplitudes"]]

    assert result["labels"] == case["labels"]
    worst = max(abs(a - b) for a, b in zip(js_amps, pennylane_amps))
    assert worst < TOLERANCE, f"{case['id']}: PennyLane and JS disagree by {worst:.3e}"


@pytest.mark.skipif(not _pennylane_available(), reason="pennylane/lightning not installed")
def test_pennylane_counts_key_puts_qubit_zero_last() -> None:
    """_to_project_bitstring must undo PennyLane's wire-0-first counts key.

    An X on qubit 0 of a 3-qubit register must come back as "001". "100" means
    the reversal was skipped and every asymmetric hardware result is mirrored.
    """
    from app.quantum.pennylane_runner import run_with_pennylane

    qasm = (
        'OPENQASM 3.0;\ninclude "stdgates.inc";\n\n'
        "qubit[3] q;\nbit[3] c;\n\nx q[0];\n\nc = measure q;\n"
    )
    result = run_with_pennylane(qasm, "aer_simulator", shots=64)
    assert list(result["counts"]) == ["001"]
