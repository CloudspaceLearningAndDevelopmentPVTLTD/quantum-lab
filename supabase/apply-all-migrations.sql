-- code change to the generator — without it, a tweak to the puzzle
-- derivation would silently rewrite history under old entries.
create table if not exists public.competitions (
  id            text primary key,          -- 'weekly-2026-W35'
  week_key      text not null,             -- '2026-W35' (ISO week)
  num_qubits    integer not null check (num_qubits between 1 and 8),
  par           integer not null check (par between 1 and 64),
  -- The target distribution, one probability per basis state. Stored
  -- as jsonb because its length is 2^num_qubits and the app treats it
  -- as an opaque array.
  target_probabilities jsonb not null,
  starts_at     timestamptz not null,      -- Monday 00:00 UTC
  ends_at       timestamptz not null,      -- next Monday 00:00 UTC
  check (ends_at > starts_at)
);

